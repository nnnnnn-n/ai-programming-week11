import pandas as pd
from analysis import 정제, 반별평균


def 테스트용_본데이터():
    """원본 파일 없이도 정제 규칙을 확인할 수 있는 114행 테스트 데이터."""
    행 = []
    for i in range(100):
        반 = "1반" if i < 50 else "2반"
        과목 = "수학" if i % 2 == 0 else "영어"
        점수 = 60 + (i % 41)
        행.append({
            "학번": f"T{i:03}", "이름": f"학생{i}",
            "반": 반, "과목": 과목, "점수": 점수
        })

    # 점수가 비어 있는 6행
    for i in range(6):
        행.append({
            "학번": f"N{i:03}", "이름": f"결측{i}",
            "반": "1반", "과목": "수학", "점수": None
        })

    # 앞의 정상 데이터와 완전히 같은 중복 4행
    행.extend([행[0].copy(), 행[1].copy(), 행[50].copy(), 행[51].copy()])

    # 점수 범위를 벗어난 4행
    for i, 점수 in enumerate([-5, 999, 999, 999]):
        행.append({
            "학번": f"X{i:03}", "이름": f"범위밖{i}",
            "반": "2반", "과목": "영어", "점수": 점수
        })
    return pd.DataFrame(행)


def 테스트용_미니데이터():
    """실습에서 제공된 mini.csv의 내용을 코드 안에 그대로 구성."""
    return pd.DataFrame([
        ["M001", "가", "1반", "수학", 90],
        ["M002", "나", "1반", "수학", 70],
        ["M003", "다", "1반", "영어", 80],
        ["M004", "라", "2반", "수학", 60],
        ["M005", "마", "2반", "수학", 100],
        ["M006", "바", "2반", "영어", 50],
        ["M007", "사", "1반", "영어", None],
        ["M002", "나", "1반", "수학", 70],
        ["M008", "아", "2반", "영어", 999],
        ["M009", "자", "1반 ", "수학", 80],
    ], columns=["학번", "이름", "반", "과목", "점수"])


본 = 정제(테스트용_본데이터())
미니 = 정제(테스트용_미니데이터())


def test_정제하면_100행이_남는다():
    assert len(본) == 100


def test_반은_두_종류만_남는다():
    assert sorted(본["반"].unique()) == ["1반", "2반"]


def test_그룹합이_전체합과_같다():
    assert 본.groupby("반")["점수"].sum().sum() == 본["점수"].sum()


def test_손계산과_일치한다():
    assert 반별평균(미니)["1반"] == 80.0
    assert 반별평균(미니)["2반"] == 70.0
